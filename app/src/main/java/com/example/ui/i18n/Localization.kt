enum class AppLanguage(
    val code: String,
    val nativeLabel: String,
    val badge: String,
    val isRtl: Boolean
) {
    AR("ar", "العربية", "AR • RTL", true),
    EN("en", "English", "EN • LTR", false),
    FR("fr", "Français", "FR • LTR", false),
    ES("es", "Español", "ES • LTR", false);

    val layoutDirection: LayoutDirection
        get() = if (isRtl) LayoutDirection.Rtl else LayoutDirection.Ltr

    companion object {
        fun fromCode(code: String?): AppLanguage =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: AR
    }
}

object LanguagePrefs {
    private const val PREF_NAME = "batch_hub_prefs"
    private const val KEY_LANG = "preferred_language"

    fun getSavedLanguage(context: Context): AppLanguage {
        val code = context.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE)
            .getString(KEY_LANG, AppLanguage.AR.code)
        return AppLanguage.fromCode(code)
    }

    fun saveLanguage(context: Context, language: AppLanguage) {
        context.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE)
            .edit()
            .putString(KEY_LANG, language.code)
            .apply()
    }
}

